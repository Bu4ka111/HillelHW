'number' + 3 + 3 // 'number33' - сначала 'number' + 3 даёт 'number3', потом + 3 даёт 'number33' (конкатенация строк)

null + 3 // 3 - null становится 0, потом 0 + 3 = 3

5 && "qwerty" // "qwerty" - оператор && возвращает последнее true значение, так как 5 это true

+'40' + +'2' + "hillel"; // "42hillel" - унарные плюсы делают '40' → 40 и '2' → 2, потом 40 + 2 = 42, а 42 + "hillel" = "42hillel"

'10' - 5 === 6; // false - сначала '10' - 5 = 5, потом 5 === 6 это false

true + false // 1 - true становится 1, false становится 0, вместе 1 + 0 = 1

'4px' - 3 // NaN - '4px' нельзя преобразовать в число, поэтому получаем NaN

'4' - 3 // 1 - строка '4' становится числом 4, потом 4 - 3 = 1

'6' + 3 ** 0; // '61' - сначала 3 ** 0 = 1, потом '6' + 1 = '61' (конкатенация)

12 / '6' // 2 - строка '6' становится числом 6, потом 12 / 6 = 2

'10' + (5 === 6); // '10false' - сначала 5 === 6 даёт false, потом '10' + false = '10false'

null == '' // false - null равен только undefined при нестрогом сравнении, а не пустой строке

3 ** (9 / 3); // 27 - сначала 9 / 3 = 3, потом 3 ** 3 = 27

!!'false' == !!'true' // true - обе строки непустые, поэтому !! делает их true, и true == true

0 || '0' && 1 // 1 - сначала '0' && 1 даёт 1 (так как '0' это true), потом 0 || 1 даёт 1

(+null == false) < 1; // false - +null = 0, 0 == false это true, true становится 1, и 1 < 1 это false

false && true || true // true - сначала false && true = false, потом false || true = true

false && (false || true); // false - сначала false || true = true, но false && true = false

(+null == false) < 1 ** 5; // false - +null = 0, 0 == false это true (становится 1), 1 ** 5 = 1, и 1 < 1 это false